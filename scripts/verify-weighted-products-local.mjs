// Runs the real migration chain in an isolated, in-memory PostgreSQL instance.
// Pass the path to @electric-sql/pglite/dist/index.js as the first argument.
import assert from "node:assert/strict";
import { readFile, readdir } from "node:fs/promises";
import { pathToFileURL } from "node:url";
const { PGlite } = await import(process.argv[2] ? pathToFileURL(process.argv[2]).href : "@electric-sql/pglite");
const db = new PGlite();
const query = async (sql, params = []) => (await db.query(sql, params)).rows;
const scalar = async (sql, params = []) => Object.values((await query(sql, params))[0])[0];
const id = (n) => `00000000-0000-4000-8000-${String(n).padStart(12, "0")}`;
const owner = id(1), business = id(2), unit = id(3), weight = id(4), method = id(5), method2 = id(6), customer = id(7);
try {
  await db.exec(`create role authenticated; create role anon;
    create schema auth; create schema storage;
    create table auth.users(id uuid primary key);
    create table auth.sessions(id uuid primary key, user_id uuid);
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
    create table storage.buckets(id text primary key, name text, public boolean, file_size_limit bigint, allowed_mime_types text[]);
    create table storage.objects(id uuid primary key, bucket_id text, name text);
    create function storage.foldername(text) returns text[] language sql immutable as $$ select string_to_array($1, '/') $$;`);
  const files = (await readdir("supabase/migrations")).filter((file) => file.endsWith(".sql")).sort();
  const weighted = files.find((file) => file.endsWith("_weighted_products.sql"));
  assert.ok(weighted);
  for (const file of files.filter((file) => file < weighted)) {
    const sql = (await readFile(`supabase/migrations/${file}`, "utf8")).replace("create extension if not exists pgcrypto;", "");
    await db.exec(sql);
  }
  await query("insert into auth.users(id) values ($1)", [owner]);
  await query("insert into public.businesses(id, name, enable_customers, enable_credits, enable_stock_adjustments, enable_multicurrency) values ($1, 'Weight QA', true, true, true, true)", [business]);
  await query("insert into public.profiles(id, business_id, full_name, role, status) values ($1,$2,'Weight QA','owner','active')", [owner, business]);
  await query("select set_config('request.jwt.claim.sub', $1, false)", [owner]);
  await query("insert into public.payment_methods(id,business_id,name) values ($1,$2,'Cash'),($3,$2,'Card')", [method, business, method2]);
  await query("insert into public.products(id,business_id,name,cost_price,sale_price,stock_quantity) values ($1,$2,'Legacy unit',4,10,10)", [unit,business]);
  const oldSale = await scalar("select public.confirm_sale($1::jsonb,$2,0,'Legacy')", [JSON.stringify([{ product_id: unit, quantity: 1 }]), method]);
  const oldSnapshot = await query("select total,total_cost,gross_profit from public.sales where id=$1", [oldSale]);
  await db.exec(await readFile(`supabase/migrations/${weighted}`, "utf8"));
  assert.deepEqual(await query("select total,total_cost,gross_profit from public.sales where id=$1", [oldSale]), oldSnapshot);
  assert.equal(await scalar("select sale_unit from public.sale_items where sale_id=$1", [oldSale]), "unit");
  assert.equal(await scalar("select stock_quantity from public.products where id=$1", [unit]), 9);
  await query("insert into public.products(id,business_id,name,cost_price,sale_price,stock_quantity,sale_unit) values ($1,$2,'Queso',6,10,5000,'weight')", [weight,business]);
  await query("insert into public.customers(id,business_id,name) values ($1,$2,'QA Customer')", [customer,business]);
  await query("update public.business_currencies set is_enabled=true, rate_mode='manual', manual_rate=100 where business_id=$1 and currency_code='VES'", [business]);
  const items = JSON.stringify([{product_id: weight, quantity: 350, sale_unit: "weight"}, {product_id: unit, quantity: 2, sale_unit: "unit"}]);
  const payments = JSON.stringify([{payment_method_id: method,amount:10},{payment_method_id:method2,amount:12.5}]);
  const sale = await scalar("select public.confirm_sale_v3($1::jsonb,$2::jsonb,$3,1,'Weighted mixed sale')", [items,payments,customer]);
  const totals = (await query("select total,total_cost,gross_profit from public.sales where id=$1", [sale]))[0];
  assert.deepEqual(totals, {total:"22.50",total_cost:"10.10",gross_profit:"12.40"});
  assert.equal(await scalar("select stock_quantity from public.products where id=$1", [weight]), 4650);
  assert.equal(await scalar("select stock_quantity from public.products where id=$1", [unit]), 7);
  assert.equal(await scalar("select rate from public.sale_exchange_rates where sale_id=$1", [sale]), "100.00000000");
  const report = await scalar("select public.business_report(current_date,current_date)");
  assert.equal(report.summary.units_sold, 3);
  assert.equal(report.summary.weight_sold_kg, 0.35);
  assert.equal(report.inventory.cost_value, 55.9);
  const saleCount = await scalar("select count(*)::int from public.sales");
  await assert.rejects(query("select public.confirm_sale($1::jsonb,$2)", [JSON.stringify([{product_id:weight,quantity:9999}]),method]), /INSUFFICIENT_STOCK/);
  await assert.rejects(query("select public.confirm_sale($1::jsonb,$2)", [JSON.stringify([{product_id:weight,quantity:1,sale_unit:"unit"}]),method]), /SALE_UNIT_CHANGED/);
  await assert.rejects(query("select public.confirm_sale_v3($1::jsonb,$2::jsonb,$3,0,'Mismatch')", [items,JSON.stringify([{payment_method_id:method,amount:1}]),customer]), /PAYMENT_TOTAL_MISMATCH/);
  assert.equal(await scalar("select count(*)::int from public.sales"), saleCount);
  assert.equal(await scalar("select stock_quantity from public.products where id=$1", [weight]),4650);
  await assert.rejects(query("update public.products set sale_unit='unit' where id=$1", [weight]), /SALE_UNIT_IMMUTABLE/);
  await query("update public.products set sale_price=11 where id=$1", [weight]);
  assert.equal(await scalar("select unit_price from public.sale_items where sale_id=$1 and product_id=$2", [sale,weight]), "10.00");
  await query("select public.void_sale($1,'QA cancellation')", [sale]);
  assert.equal(await scalar("select stock_quantity from public.products where id=$1", [weight]),5000);
  await assert.rejects(query("select public.void_sale($1,'Again')", [sale]), /SALE_ALREADY_VOIDED/);
  await query("update public.products set sale_price=10 where id=$1", [weight]);
  const credit = await scalar("select public.confirm_credit_sale($1::jsonb,$2,current_date+1,0,'Credit')", [JSON.stringify([{product_id:weight,quantity:1250,sale_unit:"weight"}]),customer]);
  assert.equal(await scalar("select balance from public.receivables where sale_id=$1", [credit]), "12.50");
  assert.equal(await scalar("select stock_quantity from public.products where id=$1", [weight]),3750);
  await query("select public.void_sale($1,'Cancel credit')", [credit]);
  assert.equal(await scalar("select status from public.receivables where sale_id=$1", [credit]), "cancelled");
  assert.equal(await scalar("select stock_quantity from public.products where id=$1", [weight]),5000);
  await query("select public.adjust_product_stock($1,5500,'QA replenishment')", [weight]);
  assert.equal(await scalar("select difference from public.inventory_adjustments where product_id=$1", [weight]),500);
  await query("update public.businesses set use_stock=false where id=$1", [business]);
  const noStock = await scalar("select public.confirm_sale($1::jsonb,$2,0,'No stock')", [JSON.stringify([{product_id:weight,quantity:10000}]),method]);
  assert.equal(await scalar("select total from public.sales where id=$1", [noStock]),"100.00");
  await query("select public.void_sale($1,'Cancel no stock')", [noStock]);
  assert.equal(await scalar("select stock_quantity from public.products where id=$1", [weight]),5500);
  await query("update public.products set sale_price=10.05 where id=$1",[weight]);
  const rounded = await scalar("select public.confirm_sale($1::jsonb,$2,0,'Round cents')", [JSON.stringify([{product_id:weight,quantity:100}]),method]);
  assert.equal(await scalar("select total from public.sales where id=$1",[rounded]),"1.01");
  await query("select set_config('request.jwt.claim.sub', '', false)");
  await assert.rejects(query("select public.confirm_sale($1::jsonb,$2)", [items,method]), /UNAUTHORIZED/);
  console.log("Weighted sales SQL checks passed: migration compatibility, mixed payments, stock, rollback, credits, cancellation, rounding, history, multicurrency, reports and authorization.");
} finally { await db.close(); }
